import { NextResponse } from "next/server";
import { writeFileSync } from "fs";
import { join } from "path";

// Only works in local dev, Vercel filesystem is read-only
export async function POST(request) {
  if (process.env.NODE_ENV !== "development") {
    return NextResponse.json({ error: "only available in dev" }, { status: 403 });
  }

  try {
    const sections = await request.json();

    const lines = sections.map((s) => {
      const fmt = (n) => Number(n).toFixed(4);
      const fmtArr = (arr) => `[${arr.map(fmt).join(", ")}]`;
      return (
        `  {\n` +
        `    px: ${fmt(s.px)}, py: ${fmt(s.py)}, scale: ${fmt(s.scale)},\n` +
        `    camZ: ${fmt(s.camZ)}, rotX: ${fmt(s.rotX)}, rotY: ${fmt(s.rotY)},\n` +
        `    freq: ${fmt(s.freq)}, amp: ${fmt(s.amp)}, speed: ${fmt(s.speed)}, fresnel: ${fmt(s.fresnel)},\n` +
        `    colorA: ${fmtArr(s.colorA)},\n` +
        `    colorB: ${fmtArr(s.colorB)},\n` +
        `    colorC: ${fmtArr(s.colorC)},\n` +
        `  }`
      );
    });

    const content =
      `// Auto-generated by blob editor, commit and push to deploy\n` +
      `export const blobStates = [\n${lines.join(",\n")},\n];\n`;

    const filePath = join(process.cwd(), "data", "blobStates.js");
    writeFileSync(filePath, content, "utf8");

    return NextResponse.json({ ok: true });
  } catch (err) {
    return NextResponse.json({ error: err.message }, { status: 500 });
  }
}
